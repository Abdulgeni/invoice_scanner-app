import 'package:invoice_scanner/core/async/cancellation_token.dart';
import 'package:invoice_scanner/features/invoice_scanner/domain/entities/invoice.dart';
import 'package:invoice_scanner/features/invoice_scanner/domain/value_objects/currency.dart';

/// Extraction layer. Knows nothing about cameras or widgets.
abstract interface class InvoiceExtractor {
  /// Reads one invoice from [imagePaths] (1 to `InvoiceLimits.maxPages`
  /// pages, in page order) in a single model call.
  ///
  /// - Missing values stay null; nothing is defaulted to zero or empty.
  /// - Values that cannot be represented exactly are listed in
  ///   `Invoice.unreadable`.
  /// - If the document shows no currency, [fallbackCurrency] is used and
  ///   `currencyAssumed` is true.
  /// - Line item ids are generated by the implementation.
  ///
  /// Timeout and bounded retry for transient errors are the
  /// implementation's job, not the caller's.
  ///
  /// Throws `InvoiceFailure` with exactly one taxonomy kind, or
  /// `CancelledException` when [cancel] fires. Must not log or embed
  /// invoice content in any error.
  Future<Invoice> extract({
    required List<String> imagePaths,
    required Currency fallbackCurrency,
    required CancellationToken cancel,
  });
}
